// Supplier item form: schema, defaults and payload mapping. Fields, order, labels and defaults follow the
// main item form (blueprint INVENTORY_ITEM_FORM) minus everything commercial / administrative. Only the
// fields the guest API accepts are ever sent (anything else is rejected with FIELD_NOT_ALLOWED).
import { z } from 'zod'

const text = (max) => z.string().trim().max(max, `Máximo ${max} caracteres`)

export const guestItemSchema = z.object({
  areaId: z.string().min(1, 'Elige una carpeta'),
  modelId: z.string().nullable(),
  model: text(255),
  categoryId: z.string().nullable(),
  brandId: z.string().nullable(),
  folio: text(50),
  serialNumber: text(255),
  assetTag: text(100),
  // Like the main form, a blank name is generated by the API (type, brand and model).
  name: text(255),
  partNumber: text(255),
  locationId: z.string().nullable(),
  status: z.enum(['available', 'maintenance']),
  conditionId: z.string().nullable(),
  warrantyExpiry: z.string().regex(/^(\d{4}-\d{2}-\d{2})?$/, 'Fecha no válida'),
  warrantyNotes: text(2000),
  notes: text(2000),
  // Keyed by custom field key (the shared custom-fields renderer binds by key); mapped to ids on submit.
  customValues: z.record(z.string(), z.any()),
})

export function guestItemDefaults(item, areaId, customFields = []) {
  const keyById = new Map(customFields.map((f) => [f.id, f.fieldKey]))
  const values = {}
  for (const cv of item?.customValues ?? []) {
    const key = keyById.get(cv.fieldId)
    if (key) values[key] = cv.value ?? ''
  }
  return {
    areaId: item?.areaId ?? areaId ?? '',
    modelId: item?.modelId ?? null,
    model: item?.model ?? '',
    categoryId: item?.categoryId ?? null,
    brandId: item?.brandId ?? null,
    folio: item?.folio ?? '',
    serialNumber: item?.serialNumber ?? '',
    assetTag: item?.assetTag ?? '',
    name: item?.name ?? '',
    partNumber: item?.partNumber ?? '',
    locationId: item?.locationId ?? null,
    status: item?.status === 'maintenance' ? 'maintenance' : 'available',
    conditionId: item?.conditionId ?? null,
    warrantyExpiry: item?.warrantyExpiry ? String(item.warrantyExpiry).slice(0, 10) : '',
    warrantyNotes: item?.warrantyNotes ?? '',
    notes: item?.notes ?? '',
    customValues: values,
  }
}

const blank = (v) => {
  const t = typeof v === 'string' ? v.trim() : v
  return t === '' || t === undefined ? null : t
}

// Custom fields that apply to the chosen type (or to every type).
export function applicableCustomFields(customFields = [], categoryId) {
  const cat = categoryId || null
  return customFields.filter((f) => !f.categoryId || f.categoryId === cat)
}

// Entries ({ field, value }) the form starts with, in the shape DynamicFieldsSection expects: the
// values the item already holds plus the required fields that apply to its type. Every other custom
// field is added on demand by the supplier, like in the main item form.
export function guestCustomEntries(item, customFields = []) {
  const byId = new Map(customFields.map((f) => [f.id, f]))
  const entries = []
  const seen = new Set()
  for (const cv of item?.customValues ?? []) {
    const field = byId.get(cv.fieldId)
    if (!field || seen.has(field.id)) continue
    seen.add(field.id)
    entries.push({ field, value: cv.value ?? '' })
  }
  for (const field of applicableCustomFields(customFields, item?.categoryId)) {
    if (field.required && !seen.has(field.id)) { seen.add(field.id); entries.push({ field: { ...field, onDemand: true }, value: '' }) }
  }
  return entries
}

// Creating sends areaId; editing never does (suppliers cannot move items).
// `statusEditable` false (assigned / retired items) leaves the admin-managed status untouched.
// `extraDefs` are the custom fields in use on the form (reported by DynamicFieldsSection); only those
// are sent, as { fieldId, value }. A field the supplier removed from an existing item is cleared (null).
export function buildGuestPayload(values, { create, extraDefs = [], statusEditable = true, originalFieldIds = [] }) {
  const cv = values.customValues ?? {}
  const used = new Set(extraDefs.map((f) => f.id))
  const customValues = extraDefs.map((f) => {
    const raw = cv[f.fieldKey]
    return { fieldId: f.id, value: raw === null || raw === undefined ? null : blank(String(raw)) }
  })
  const removed = Array.isArray(cv.__removed) ? cv.__removed : []
  for (const id of removed) if (originalFieldIds.includes(id) && !used.has(id)) customValues.push({ fieldId: id, value: null })
  const payload = {
    modelId: blank(values.modelId),
    model: blank(values.model),
    categoryId: blank(values.categoryId),
    brandId: blank(values.brandId),
    folio: blank(values.folio),
    serialNumber: blank(values.serialNumber),
    assetTag: blank(values.assetTag),
    name: values.name.trim(),
    partNumber: blank(values.partNumber),
    locationId: blank(values.locationId),
    conditionId: blank(values.conditionId),
    warrantyExpiry: blank(values.warrantyExpiry),
    warrantyNotes: blank(values.warrantyNotes),
    notes: blank(values.notes),
    customValues,
  }
  if (statusEditable) payload.status = values.status
  return create ? { areaId: values.areaId, ...payload } : payload
}
