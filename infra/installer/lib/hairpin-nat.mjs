// Hairpin NAT (NAT loopback) detection for instances behind a home/office
// router. When a public hostname resolves to the router's WAN IP, a request
// from inside the LAN must be "looped back" through the port forward to reach
// this host. Many ISP routers don't do that and answer on :443 themselves with
// their admin UI's self-signed certificate, so the API container's call to the
// public LiveKit URL fails even though the instance works from the internet.
//
// Detection is deliberately narrow so healthy instances are untouched: a
// hostname is only treated as hairpinned when the public probe fails at the
// TLS/network level AND the same hostname served by this host's own proxy
// (127.0.0.1, SNI = hostname) presents a valid certificate. Only then do the
// containers get `<hostname>:host-gateway` so they reach the host proxy
// directly instead of the router.
import https from "node:https";
import fs from "node:fs/promises";

export const HAIRPIN_OVERRIDE_FILENAME = "docker-compose.hairpin.yml";

// Services that call public Runly/LiveKit/Storage URLs server-side (egress
// uploads recordings to the public Supabase S3 endpoint).
const HAIRPIN_SERVICES = [
  "runly-api-local",
  "runly-worker-local",
  "runly-api-external",
  "runly-worker-external",
  "runly-transcriber-local",
  "runly-transcriber-external",
  "runly-backup-local",
  "runly-backup-external",
  "collabora",
  "egress",
];

// On Linux these run with network_mode: host (docker-compose.linux.yml), where
// host-gateway is the docker0 bridge address; 127.0.0.1 is the host proxy.
export const LINUX_HOST_NETWORK_SERVICES = ["egress"];

const TLS_OR_NETWORK_ERROR = /CERT|SELF_SIGNED|TLS|SSL|ECONNREFUSED|ECONNRESET|ETIMEDOUT|EHOSTUNREACH|ENETUNREACH|EPROTO|TIMEOUT/i;

// Resolves { ok, status, code, error }. `ok` means a TLS-verified HTTP response
// (any status). `address` overrides where we connect while keeping SNI and
// certificate verification bound to `hostname`.
export function httpsProbe({ hostname, address, port = 443, path = "/", timeoutMs = 8_000 }) {
  return new Promise((resolve) => {
    const request = https.request({
      host: address || hostname,
      servername: hostname,
      port,
      path,
      method: "GET",
      headers: { Host: hostname, "User-Agent": "runlyerp-installer" },
      rejectUnauthorized: true,
      timeout: timeoutMs,
    }, (response) => {
      response.resume();
      resolve({ ok: true, status: response.statusCode ?? 0 });
    });
    request.on("timeout", () => request.destroy(Object.assign(new Error("timeout"), { code: "ETIMEDOUT" })));
    request.on("error", (error) => resolve({ ok: false, code: error.code ?? "", error: error.message }));
    request.end();
  });
}

export function collectPublicHttpsHosts({ domains = [], urls = [] } = {}) {
  const hosts = new Set();
  for (const domain of domains) {
    const value = String(domain ?? "").trim().toLowerCase();
    if (value) hosts.add(value);
  }
  for (const raw of urls) {
    try {
      const url = new URL(String(raw ?? "").trim().replace(/^wss:/i, "https:"));
      if (url.protocol === "https:" && !/^\d+\.\d+\.\d+\.\d+$/.test(url.hostname) && url.hostname !== "localhost") {
        hosts.add(url.hostname.toLowerCase());
      }
    } catch { /* not a URL */ }
  }
  return [...hosts];
}

export async function detectHairpinHosts(hostnames, { probe = httpsProbe } = {}) {
  const hairpinned = [];
  for (const hostname of hostnames) {
    const publicResult = await probe({ hostname });
    if (publicResult.ok) continue;
    if (!TLS_OR_NETWORK_ERROR.test(`${publicResult.code} ${publicResult.error}`)) continue;
    const loopbackResult = await probe({ hostname, address: "127.0.0.1" });
    if (loopbackResult.ok) hairpinned.push({ hostname, publicError: publicResult.error || publicResult.code });
  }
  return hairpinned;
}

export function renderHairpinComposeOverride(hostnames, { hostNetworkServices = [] } = {}) {
  const services = HAIRPIN_SERVICES.map((service) => {
    const target = hostNetworkServices.includes(service) ? "127.0.0.1" : "host-gateway";
    const hostLines = hostnames.map((hostname) => `      - "${hostname}:${target}"`).join("\n");
    return `  ${service}:\n    extra_hosts:\n${hostLines}`;
  }).join("\n");
  return `# GENERATED by the Runly installer — do not edit. Present only when this host's
# router does not do NAT loopback (see lib/hairpin-nat.mjs); deleted
# automatically once the public hostnames are reachable from inside the LAN.\n\nservices:\n${services}\n`;
}

// Detects hairpinned hostnames, writes/removes the override file and returns
// { hostnames, composeArgs } — composeArgs is ["-f", file] or [].
export async function configureHairpinNat({ hostnames, overrideFile, hostNetworkServices = [], probe = httpsProbe, log = console.log }) {
  const detected = hostnames.length ? await detectHairpinHosts(hostnames, { probe }) : [];
  if (!detected.length) {
    await fs.rm(overrideFile, { force: true });
    return { hostnames: [], composeArgs: [] };
  }
  const names = detected.map((item) => item.hostname);
  await fs.writeFile(overrideFile, renderHairpinComposeOverride(names, { hostNetworkServices }), "utf8");
  log("  NAT loopback: the router does not loop public requests back to this host.");
  for (const item of detected) log(`    ${item.hostname}: public probe failed (${item.publicError}); local proxy certificate is valid.`);
  log("    Containers will reach these hostnames through the host proxy.");
  log("    LAN browsers need local DNS pointing these names to this host's private IP.");
  return { hostnames: names, composeArgs: ["-f", overrideFile] };
}

// Public health check for the installer itself (runs on the host, which has
// the same loopback problem): hairpinned hostnames are checked via 127.0.0.1.
export function probePublicHealth(publicUrl, hairpinHosts = []) {
  const url = new URL(publicUrl.replace(/^wss:/i, "https:"));
  return httpsProbe({
    hostname: url.hostname,
    address: hairpinHosts.includes(url.hostname.toLowerCase()) ? "127.0.0.1" : undefined,
    port: Number(url.port) || 443,
    path: url.pathname || "/",
    timeoutMs: 10_000,
  });
}
