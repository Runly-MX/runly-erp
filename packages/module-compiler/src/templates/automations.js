// Generates api/automations.js (+ api/events.js for event triggers) from
// definition.automations. Spec docs/superpowers/specs/2026-10-04-builder-automations-design.md §4.3
// and 2026-10-24-automation-studio-v2-design.md (steps, run log).
// The runtime is inlined so a published module needs nothing beyond
// moduleContext.services (record triggers) and the dispatcher's `services`
// (event triggers).
import { SERVICE_CONTRACTS, isEmpty, matches, render, sourceValue, buildArgs } from '@runly/module-engine/contracts'
import { stepsOf } from '../automations.js'

// Serialize only trusted official functions; no user code is evaluated.
function automationRuntimeSource() {
  return 'const isEmpty = ' + isEmpty.toString() + '\n\n' + [matches, render, sourceValue, buildArgs].map(fn => 'export ' + fn.toString()).join('\n\n')
}

export function hasAutomations(config) {
  return Boolean(config.automations?.length)
}

export function hasEventAutomations(config) {
  return (config.automations ?? []).some((automation) => automation.trigger.type === 'event')
}

export function recordAutomationsFor(config, entityKey) {
  return (config.automations ?? []).filter((automation) => automation.trigger.type === 'record' && automation.trigger.entity === entityKey)
}

// Per step, what the runtime needs to know about the contract. v1 `action`
// definitions are normalized to `steps` here.
function withRuntime(automation) {
  const { action, ...rest } = automation
  return {
    ...rest,
    steps: stepsOf(automation).map((step) => {
      const args = SERVICE_CONTRACTS[step.service]?.args ?? {}
      return {
        service: step.service,
        args: step.args ?? {},
        runtime: {
          arrayArgs: Object.entries(args).filter(([, spec]) => spec.type.endsWith('[]')).map(([name]) => name),
          acceptsSource: Boolean(args.sourceEntityId),
        },
      }
    }),
  }
}

export function generateAutomationsModule(config) {
  const list = config.automations.map(withRuntime)
  return `// Generated by the Module Builder from the module's automations. Edit them in
// the Builder (Automatizaciones), not here: this file is rewritten on publish.
export const MODULE_KEY = ${JSON.stringify(config.key)}
export const AUTOMATIONS = ${JSON.stringify(list, null, 2)}

${automationRuntimeSource()}

// Runs the steps of one automation in order. Each step gets its own
// idempotency key (<base>, then <base>:<index> from the second step; the first
// keeps the v1 key so republishing never repeats work) so a retried event never repeats finished
// steps. With onError "stop" (default) the steps after a failure are skipped.
export async function runSteps({ automation, services, base, data, recordId = null, actorId = null }) {
  const steps = []
  let failed = false
  for (let index = 0; index < automation.steps.length; index += 1) {
    const step = automation.steps[index]
    if (failed && automation.onError !== 'continue') { steps.push({ index, service: step.service, ok: false, skipped: true }); continue }
    try {
      await services.call(step.service, buildArgs(automation, { step: index, data, recordId, actorId, idempotencyKey: base ? (index ? base + ':' + index : base) : null }))
      steps.push({ index, service: step.service, ok: true })
    } catch (error) {
      failed = true
      console.error('[automatizaciones] ' + automation.key + ' paso ' + (index + 1) + ':', error?.message ?? error)
      steps.push({ index, service: step.service, ok: false, code: error?.code ?? null, error: String(error?.message ?? error) })
    }
  }
  const failures = steps.filter((step) => !step.ok && !step.skipped)
  return { key: automation.key, ok: !failures.length, steps, code: failures[0]?.code ?? null, error: failures.map((step) => step.error).join(' | ') || null }
}

// One run-log row per execution; logging never breaks the save or the event.
function runEntry(result, { trigger, ref, startedAt }) {
  const done = result.steps.filter((step) => step.ok).length
  return {
    moduleKey: MODULE_KEY, automationKey: result.key, triggerKind: trigger, triggerRef: ref ?? null,
    status: result.ok ? 'success' : (done ? 'partial' : 'failed'),
    steps: result.steps, error: result.error, durationMs: Date.now() - startedAt,
  }
}

// Runs after a record is created/updated. Never throws: a failed automation
// does not undo the save; the route returns the results and logs the error.
export async function runRecordAutomations({ c, moduleContext, entity, on, record, previous = null }) {
  const due = AUTOMATIONS.filter((a) => a.enabled && a.trigger.type === 'record' && a.trigger.entity === entity
    && (a.trigger.on === 'save' || a.trigger.on === on) && matches(a.trigger.when, record, previous))
  if (!due.length || !record) return []
  const services = moduleContext?.services?.forRequest?.(c)
  if (!services) return due.map((a) => ({ key: a.key, ok: false, error: 'Los servicios no están disponibles en esta instancia.' }))
  const actorId = c.get('userId') ?? null
  const results = []
  for (const automation of due) {
    const startedAt = Date.now()
    const result = await runSteps({ automation, services, base: on === 'create' ? automation.key + ':' + record.id + ':create' : null, data: record, recordId: record.id, actorId })
    try { await moduleContext?.automations?.log?.(c, runEntry(result, { trigger: 'record', ref: record.id, startedAt })) } catch { /* the log is best effort */ }
    results.push({ key: result.key, ok: result.ok, ...(result.ok ? {} : { code: result.code, error: result.error }) })
  }
  return results
}

// api/events.js handlers: every matching automation, idempotent per event; a
// failure is rethrown after the loop so the dispatcher retries.
export function createEventHandlers() {
  const handlers = {}
  const events = [...new Set(AUTOMATIONS.filter((a) => a.trigger.type === 'event').map((a) => a.trigger.event))]
  for (const event of events) {
    handlers[event] = async ({ payload, eventId, log, services }) => {
      const due = AUTOMATIONS.filter((a) => a.enabled && a.trigger.type === 'event' && a.trigger.event === event && matches(a.trigger.when, payload))
      if (!due.length) return
      if (!services) throw new Error('Los servicios no están disponibles en esta instancia.')
      const failures = []
      for (const automation of due) {
        const startedAt = Date.now()
        const result = await runSteps({ automation, services, base: automation.key + ':' + eventId, data: payload })
        try { await log?.(runEntry(result, { trigger: 'event', ref: eventId, startedAt })) } catch { /* the log is best effort */ }
        if (!result.ok) failures.push(automation.key + ': ' + result.error)
      }
      if (failures.length) throw new Error(failures.join(' | '))
    }
  }
  return handlers
}
`
}

export function generateAutomationEvents() {
  return `// Generated by the Module Builder: system events that trigger automations.
import { createEventHandlers } from './automations.js'

export const handlers = createEventHandlers()
`
}
