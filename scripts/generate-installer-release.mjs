import { readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'

const directory = 'infra/installer'
const catalog = JSON.parse(readFileSync(`${directory}/release-files.json`, 'utf8'))
const check = process.argv.includes('--check')
const canonical = value => value.toString('utf8').replaceAll('\r\n', '\n')
const hash = text => createHash('sha256').update(text).digest('hex')
const outputs = new Map()
const loaderHash = hash(canonical(readFileSync(`${directory}/update-installer.mjs`)))
for (const mode of ['local', 'external']) {
  const sh = `#!/usr/bin/env bash
# Generated by scripts/generate-installer-release.mjs. Requires Node 18+ and curl.
set -euo pipefail
DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"
REF="\${RUNLY_INSTALLER_REF:-}"
if [[ -z "$REF" ]]; then
  REF=$(curl --proto '=https' --tlsv1.2 -fsS https://api.github.com/repos/Runly-MX/runly-erp/git/ref/heads/main | node -e 'let s="";process.stdin.on("data",c=>s+=c);process.stdin.on("end",()=>{process.stdout.write(JSON.parse(s).object.sha)})')
fi
[[ "$REF" =~ ^[a-f0-9]{40}$ ]] || { echo "INSTALLER_IMMUTABLE_REF_REQUIRED" >&2; exit 1; }
LOADER=$(mktemp)
mv "$LOADER" "$LOADER.mjs"
LOADER="$LOADER.mjs"
trap 'rm -f "$LOADER"' EXIT
curl --proto '=https' --tlsv1.2 -fsSLo "$LOADER" "https://raw.githubusercontent.com/Runly-MX/runly-erp/$REF/infra/installer/update-installer.mjs"
node -e 'const fs=require("node:fs"),crypto=require("node:crypto");if(crypto.createHash("sha256").update(fs.readFileSync(process.argv[1])).digest("hex")!=="${loaderHash}")throw Error("INSTALLER_LOADER_INTEGRITY_FAILED: refresh bootstrap for the selected commit")' "$LOADER"
RUN=()
${mode === 'local' ? '[[ "${1:-}" == "--skip-run" ]] || RUN=(--run)' : '[[ "${1:-}" != "--run" ]] || RUN=(--run)'}
node "$LOADER" --mode=${mode} --root="$DIR" --ref="$REF" "\${RUN[@]}"
`
  const ps = `# Generated by scripts/generate-installer-release.mjs. Requires Node 18+.
param([switch]$SkipRun, [switch]$SkipEnvCopy, [switch]$SkipBootstrapRefresh, [switch]$Run)
$ErrorActionPreference = "Stop"
$ref = $env:RUNLY_INSTALLER_REF
if (-not $ref) { $ref = (Invoke-RestMethod -Uri "https://api.github.com/repos/Runly-MX/runly-erp/git/ref/heads/main").object.sha }
if ($ref -notmatch '^[a-f0-9]{40}$') { throw "INSTALLER_IMMUTABLE_REF_REQUIRED" }
$loader = Join-Path ([IO.Path]::GetTempPath()) (([Guid]::NewGuid().ToString()) + ".mjs")
try {
  Invoke-WebRequest -Uri "https://raw.githubusercontent.com/Runly-MX/runly-erp/$ref/infra/installer/update-installer.mjs" -OutFile $loader
  if ((Get-FileHash -LiteralPath $loader -Algorithm SHA256).Hash.ToLowerInvariant() -ne "${loaderHash}") { throw "INSTALLER_LOADER_INTEGRITY_FAILED: refresh bootstrap for the selected commit" }
  $forwarded = @("--mode=${mode}", "--root=$PSScriptRoot", "--ref=$ref")
  ${mode === 'local' ? 'if (-not $SkipRun) { $forwarded += "--run" }' : 'if ($Run) { $forwarded += "--run" }'}
  if ($SkipEnvCopy) { $forwarded += "--skip-env-copy" }
  & node $loader @forwarded
  if ($LASTEXITCODE -ne 0) { throw "INSTALLER_UPDATE_FAILED" }
} finally { if (Test-Path -LiteralPath $loader) { Remove-Item -LiteralPath $loader -Force } }
`
  outputs.set(`bootstrap-${mode}.sh`, sh)
  outputs.set(`bootstrap-${mode}.ps1`, ps)
}
const legacy = {}
const log = execFileSync('git', ['log', '--format=', '--raw', '--no-abbrev', '--no-renames', '--', directory], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })
for (const line of log.split('\n')) {
  const match = /^:\d+ \d+ ([a-f0-9]{40}) ([a-f0-9]{40}) [A-Z]\tinfra\/installer\/(.+)$/.exec(line)
  if (!match) continue
  legacy[match[3]] ??= new Set()
  for (const blob of match.slice(1, 3)) if (!/^0+$/.test(blob)) legacy[match[3]].add(blob)
}
const files = {}
for (const mode of ['local', 'external']) for (const file of catalog.modes[mode]) {
  const text = outputs.get(file) ?? canonical(readFileSync(`${directory}/${file}`))
  const blob = createHash('sha1').update(`blob ${Buffer.byteLength(text)}\0`).update(text).digest('hex')
  if (!files[file]) files[file] = { sha256: hash(text), modes: [], legacyGitBlobs: [...(legacy[file] ?? [])].filter(value => value !== blob).sort() }
  files[file].modes.push(mode)
}
outputs.set('installer-release.json', JSON.stringify({ schema: 1, contract: 'studio-realtime-1', version: catalog.version, files }, null, 2) + '\n')
for (const [file, text] of outputs) {
  if (check) {
    if (canonical(readFileSync(`${directory}/${file}`)) !== text) throw Error(`INSTALLER_RELEASE_STALE: run node scripts/generate-installer-release.mjs (${file})`)
  } else writeFileSync(`${directory}/${file}`, text)
}
console.log(check ? 'Installer manifest and bootstrap integrity: OK' : 'Installer manifest and bootstrap generated')
